// Public entry code only. GAS source, credentials and runtime device data must
// never be included in this bundle. config.js stays independently editable.
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.join(__dirname,'../board-pwa');
const sources=['connection-diagnostics.js','entry-session.js','app.js'];
const output='/* Generated by scripts/build-entry.cjs. Edit the source modules. */\n'+sources.map(name=>{
  const text=fs.readFileSync(path.join(root,name),'utf8');new vm.Script(text,{filename:name});
  return '\n;/* '+name+' */\n'+text;
}).join('\n');
new vm.Script(output,{filename:'entry-startup.js'});
const destination=path.join(root,'entry-startup.js');
if(process.argv.includes('--check')){
  if(!fs.existsSync(destination)||fs.readFileSync(destination,'utf8')!==output)throw Error('Run node scripts/build-entry.cjs to update the entry bundle.');
}else fs.writeFileSync(destination,output);
console.log('Entry startup bundle '+(process.argv.includes('--check')?'verified':'built'));
